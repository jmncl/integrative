const mongoose = require('mongoose')
const { assignNumber } = require('./counter')

const orderSchema = mongoose.Schema({
    _id: Number,
    shippingInfo: {
        address: {
            type: String,
            required: true
        },
        city: {
            type: String,
            required: true
        },
        phoneNo: {
            type: String,
            required: true
        },
        postalCode: {
            type: String,
            required: true
        },
        country: {
            type: String,
            required: true
        }
    },
    user: {
        type: Number,
        required: true,
        ref: 'User'
    },
    orderItems: [
        {
            name: {
                type: String,
                required: true
            },
            quantity: {
                type: Number,
                required: true
            },
            image: {
                type: String,
                required: true
            },
            price: {
                type: Number,
                required: true
            },
            product: {
                type: Number,
                required: true,
                ref: 'Product'
            },
            size: {
                type: String
            }
        }
    ],
    paymentInfo: {
        id: {
            type: String
        },
        status: {
            type: String
        }
    },
    paidAt: {
        type: Date
    },

    itemsPrice: {
        type: Number,
        required: true,
        default: 0.0
    },
    taxPrice: {
        type: Number,
        required: true,
        default: 0.0
    },
    shippingPrice: {
        type: Number,
        required: true,
        default: 0.0
    },
    totalPrice: {
        type: Number,
        required: true,
        default: 0.0
    },
    orderStatus: {
        type: String,
        required: true,
        default: 'Processing'
    },
    deliveredAt: {
        type: Date
    },
    code: {
        type: String
    },
    createdAt: {
        type: Date,
        default: Date.now
    }

})

orderSchema.pre('save', async function () {
    await assignNumber('Order').call(this)
    if (!this.code && typeof this._id === 'number') {
        this.code = `JO${this._id}`
    }
})

module.exports = mongoose.model('Order', orderSchema)